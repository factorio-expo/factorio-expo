// Generates src/public.d.ts and src/admin.d.ts, the types of the expo-api's
// public and staff listeners, from their checked-in OpenAPI documents.
// `pnpm generate` after a document changes; generate.test.ts fails while a
// file is stale.
import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

/** One listener's document and the declarations generated from it. */
export const listeners = {
	public: {
		spec: new URL("../../../apps/expo-api/openapi/public.json", import.meta.url),
		output: new URL("public.d.ts", import.meta.url),
		source: "apps/expo-api/openapi/public.json",
	},
	admin: {
		spec: new URL("../../../apps/expo-api/openapi/admin.json", import.meta.url),
		output: new URL("admin.d.ts", import.meta.url),
		source: "apps/expo-api/openapi/admin.json",
	},
} as const;

export type Listener = keyof typeof listeners;

/** The generated declarations of one listener. */
export async function generate(listener: Listener): Promise<string> {
	const { spec: specUrl, source } = listeners[listener];
	const header = `// Generated by packages/expo-api-types (pnpm generate) from
// ${source}. Do not edit.

`;
	const spec: unknown = JSON.parse(await readFile(specUrl, "utf8"));
	// oxlint-disable-next-line typescript/no-unsafe-type-assertion -- the document is the API's own, checked by its Go test
	const ast = await openapiTS(spec as Parameters<typeof openapiTS>[0], {
		rootTypes: true,
		rootTypesNoSchemaPrefix: true,
	});
	return header + astToString(ast);
}

function isListener(key: string): key is Listener {
	return ["admin", "public"].includes(key);
}

if (import.meta.main) {
	await Promise.all(
		Object.keys(listeners)
			.filter((l) => isListener(l))
			.map(async (listener) =>
				writeFile(listeners[listener].output, await generate(listener), { flag: "w" }),
			),
	);
}
