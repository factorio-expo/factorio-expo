package assets

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"factorio-expo/apps/expo-game-data/internal/prototypes"
)

// PickerFile is the web app source file the icon picker lists go to.
const PickerFile = "icon-picker.data.ts"

// WritePicker writes the icon picker lists as TypeScript to sourceDirectory.
func WritePicker(sourceDirectory string, picker prototypes.Picker) error {
	source, err := PickerTypeScript(picker)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(sourceDirectory, 0o755); err != nil {
		return fmt.Errorf("create icon picker data directory: %w", err)
	}
	if err := os.WriteFile(filepath.Join(sourceDirectory, PickerFile), source, 0o644); err != nil {
		return fmt.Errorf("write icon picker data: %w", err)
	}
	return nil
}

// PickerTypeScript renders the picker as a TypeScript module, one subgroup
// row per line.
func PickerTypeScript(picker prototypes.Picker) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString("// Generated by expo-game-data from the game's item groups; do not edit.\n\n")
	kinds := make([]string, len(prototypes.PickerKinds))
	for i, kind := range prototypes.PickerKinds {
		kinds[i] = strconv.Quote(string(kind))
	}
	fmt.Fprintf(&out, "export type IconPickerKind = %s;\n\n", strings.Join(kinds, " | "))
	out.WriteString("/** One tab: an item group, with one row of rich-text tokens per subgroup. */\n")
	out.WriteString("export interface IconPickerGroup {\n\tname: string;\n\trows: string[][];\n}\n\n")
	out.WriteString("export const iconPicker: Record<IconPickerKind, IconPickerGroup[]> = {\n")
	for _, kind := range prototypes.PickerKinds {
		fmt.Fprintf(&out, "\t%s: [\n", strconv.Quote(string(kind)))
		for _, group := range picker[kind] {
			fmt.Fprintf(&out, "\t\t{\n\t\t\tname: %s,\n\t\t\trows: [\n", strconv.Quote(group.Name))
			for _, row := range group.Rows {
				encoded, err := json.Marshal(row)
				if err != nil {
					return nil, fmt.Errorf("encode icon picker row: %w", err)
				}
				fmt.Fprintf(&out, "\t\t\t\t%s,\n", encoded)
			}
			out.WriteString("\t\t\t],\n\t\t},\n")
		}
		out.WriteString("\t],\n")
	}
	out.WriteString("};\n")
	return out.Bytes(), nil
}
