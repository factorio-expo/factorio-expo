// Package mods detects which mods a blueprint needs from the entity and
// recipe names it uses, against the name table expo-game-data generates
// (modsets.json, embedded; regenerate it, never edit it by hand).
package mods

import (
	"crypto/sha256"
	_ "embed"
	"encoding/hex"
	"fmt"
	"slices"
	"sort"
	"sync"

	"factorio-expo/internal/modtable"
)

//go:embed modsets.json
var embedded []byte

// Table answers which modsets define a name.
type Table struct {
	version  string
	modsets  []modtable.Modset
	base     int
	entities map[string][]int
	recipes  map[string][]int
}

// Embedded is the table built into this binary. A broken generated file
// panics: it is checked in, and TestEmbeddedTableLoads catches it first.
var Embedded = sync.OnceValue(func() *Table {
	table, err := New(embedded)
	if err != nil {
		panic(fmt.Sprintf("embedded mod table: %v", err))
	}
	return table
})

// New builds a table from generated bytes. It must contain the base modset.
func New(data []byte) (*Table, error) {
	parsed, err := modtable.Parse(data)
	if err != nil {
		return nil, err
	}
	sum := sha256.Sum256(data)
	table := &Table{
		version:  hex.EncodeToString(sum[:])[:16],
		modsets:  parsed.Modsets,
		base:     -1,
		entities: map[string][]int{},
		recipes:  map[string][]int{},
	}
	for index, modset := range parsed.Modsets {
		if modset.Name == "base" && modset.Builtin {
			table.base = index
		}
		for _, name := range modset.Entities {
			table.entities[name] = append(table.entities[name], index)
		}
		for _, name := range modset.Recipes {
			table.recipes[name] = append(table.recipes[name], index)
		}
	}
	if table.base < 0 {
		return nil, fmt.Errorf("mod table has no built-in base modset")
	}
	return table, nil
}

// Version changes whenever the table does; stored detections carry it so a
// new table re-detects them.
func (t *Table) Version() string {
	return t.version
}

// Match is one modset the blueprint needs, or probably needs.
type Match struct {
	Name  string `json:"name" doc:"The modset's name."`
	Title string `json:"title" doc:"The modset's display name."`
	// Builtin marks the game's own mods (elevated-rails, quality, recycler,
	// space-age): a name only they define is an exact match.
	Builtin bool `json:"builtin" doc:"Whether it is one of the game's own mods (elevated-rails, quality, recycler, space-age): a name only they define is an exact match."`
	// Score is 1 for a built-in match; for any other modset, the share of
	// the blueprint's non-vanilla names it defines (names several modsets
	// define count for each).
	Score float64 `json:"score" doc:"1 for a built-in match; for any other modset, the share of the blueprint's non-vanilla names it defines."`
}

// Detection is what a blueprint needs beyond the base game.
type Detection struct {
	// Modsets lists built-in matches first (table order), then the others
	// by score, best first.
	Modsets []Match `json:"modsets" doc:"The matching modsets: built-in ones first, then the others by score, best first."`
	// UnknownEntities and UnknownRecipes are names no modset defines: an
	// unlisted mod, or a typo.
	UnknownEntities []string `json:"unknown_entities" doc:"Entity names no modset defines: an unlisted mod, or a typo."`
	UnknownRecipes  []string `json:"unknown_recipes" doc:"Recipe names no modset defines."`
}

// Detect matches entity and recipe names (duplicates are fine). Base names
// count for nothing. A name a built-in mod defines is attributed to it alone;
// the remaining names score every other modset that defines them.
func (t *Table) Detect(entities, recipes []string) Detection {
	detection := Detection{Modsets: []Match{}, UnknownEntities: []string{}, UnknownRecipes: []string{}}
	builtin := map[int]bool{}
	explained := map[int]int{}
	modded := 0
	visit := func(names []string, owners map[string][]int, unknown *[]string) {
		seen := map[string]bool{}
		for _, name := range names {
			if seen[name] {
				continue
			}
			seen[name] = true
			indexes := owners[name]
			if t.has(indexes, t.base) {
				continue
			}
			builtinOwners := 0
			for _, index := range indexes {
				if t.modsets[index].Builtin {
					builtin[index] = true
					builtinOwners++
				}
			}
			if builtinOwners > 0 {
				continue
			}
			modded++
			if len(indexes) == 0 {
				*unknown = append(*unknown, name)
				continue
			}
			for _, index := range indexes {
				explained[index]++
			}
		}
		sort.Strings(*unknown)
	}
	visit(entities, t.entities, &detection.UnknownEntities)
	visit(recipes, t.recipes, &detection.UnknownRecipes)

	for index, modset := range t.modsets {
		if builtin[index] {
			detection.Modsets = append(detection.Modsets, Match{Name: modset.Name, Title: modset.Title, Builtin: true, Score: 1})
		}
	}
	var others []Match
	for index, count := range explained {
		modset := t.modsets[index]
		others = append(others, Match{Name: modset.Name, Title: modset.Title, Score: float64(count) / float64(modded)})
	}
	sort.Slice(others, func(i, j int) bool {
		if others[i].Score != others[j].Score {
			return others[i].Score > others[j].Score
		}
		return others[i].Name < others[j].Name
	})
	detection.Modsets = append(detection.Modsets, others...)
	return detection
}

// DefinesEntity and DefinesRecipe report whether any modset (the base game
// included) defines the name: a prototype name of the pinned game or a
// listed mod.
func (t *Table) DefinesEntity(name string) bool { return len(t.entities[name]) > 0 }

func (t *Table) DefinesRecipe(name string) bool { return len(t.recipes[name]) > 0 }

func (t *Table) has(indexes []int, want int) bool {
	return slices.Contains(indexes, want)
}

// Search filter values (the entries index's mods field).
const (
	// Vanilla marks an entry that needs nothing beyond the base game.
	Vanilla = "vanilla"
	// SpaceAge stands for every built-in mod beyond base (space-age,
	// quality, recycler, elevated-rails): the Space Age expansion.
	SpaceAge = "space-age"
)

// IsVanilla reports whether the blueprint needs nothing beyond base.
func (d Detection) IsVanilla() bool {
	return len(d.Modsets) == 0 && len(d.UnknownEntities) == 0 && len(d.UnknownRecipes) == 0
}

// SearchValues are the filter values the detection matches besides Vanilla:
// SpaceAge for any built-in match, then each other modset's name.
func (d Detection) SearchValues() []string {
	var values []string
	expansion := false
	for _, match := range d.Modsets {
		if match.Builtin {
			expansion = true
			continue
		}
		values = append(values, match.Name)
	}
	if expansion {
		values = append([]string{SpaceAge}, values...)
	}
	return values
}

// BadgeMinScore is the lowest score at which a guessed (non built-in) modset
// is shown as a badge; below it the guess stays on the leaf page only.
const BadgeMinScore = 0.5

// Badges are the mods shown as badges on cards, by search filter value (the
// same values `mods=` takes, so a badge links to its search): SpaceAge when a
// built-in mod is needed, then every other modset scoring at least
// BadgeMinScore. The web resolves titles from GET /api/v1/modsets.
func (d Detection) Badges() []string {
	badges := []string{}
	for _, match := range d.Modsets {
		if match.Builtin {
			if len(badges) == 0 {
				badges = append(badges, SpaceAge)
			}
			continue
		}
		if match.Score >= BadgeMinScore {
			badges = append(badges, match.Name)
		}
	}
	return badges
}

// Listed is a modset as the search filter offers it.
type Listed struct {
	Name  string `json:"name" doc:"The modset's name, a value of the search mods filter."`
	Title string `json:"title" doc:"The modset's display name."`
}

// Listed returns the modsets that are not built-in mods, in table order.
func (t *Table) Listed() []Listed {
	listed := []Listed{}
	for _, modset := range t.modsets {
		if !modset.Builtin {
			listed = append(listed, Listed{Name: modset.Name, Title: modset.Title})
		}
	}
	return listed
}
